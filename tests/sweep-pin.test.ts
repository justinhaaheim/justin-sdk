/**
 * Tests for the sweep's PIN WRITE — home-base-apus.1.
 *
 * THE CONTRACT UNDER TEST: after the pin step, package.json declares
 * `@justinhaaheim/justin-sdk` EXACTLY ONCE, in devDependencies, at the swept
 * pin — from any of the four manifest shapes the fleet actually holds — and a
 * repo whose SDK comes from a WORKSPACE MEMBER gets no pin written at all.
 *
 * WHY THESE RUN THE REAL PACKAGE MANAGERS. Every bug this fixes is a bug in
 * what `bun`/`npm`/`yarn` DO to a manifest, not in what this module believes
 * they do. A faked runner would have asserted my model of bun and passed while
 * the fleet burned — the maiden real sweep took 4 of its first 6 repos red on
 * exactly such an assumption. So the fixtures shell out for real.
 *
 * WHY THE PIN IS A `file:` SPEC HERE. Real managers, no network: the pin string
 * is a parameter of `writeSdkPin`, so a local fixture package stands in for the
 * github spec. What that costs is stated plainly rather than papered over — the
 * `DependencyLoop` arm is github-resolution-shaped and CANNOT be reproduced
 * offline. Its measurement lives on home-base-apus.1 (verbatim error, four
 * arms) and its real proof is the fleet re-sweep, where every repo that failed
 * has precisely that shape. What the `file:` pin DOES reproduce offline is the
 * same precondition — "the package is already declared at a different spec" —
 * and bun's other, quieter answer to it: the same key written twice into one
 * object.
 */

