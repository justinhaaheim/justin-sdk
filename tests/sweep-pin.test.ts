describe('countSdkKeyDeclarations', () => {
  test('counts declarations, not mentions — a script alias naming the SDK is not one', () => {
    const text = JSON.stringify(
      {
        devDependencies: {[SDK_PKG]: 'github:justinhaaheim/justin-sdk#v1.0.0'},
        scripts: {
          doctor: `bunx ${SDK_PKG} doctor`,
          signal: `bunx ${SDK_PKG} signal`,
        },
      },
      null,
      2,
    );
    expect(countSdkKeyDeclarations(text)).toBe(1);
  });

  test('sees the duplicate KEY that JSON.parse hides', () => {
    // Hand-written because JSON.stringify cannot express it — which is the
    // point: this shape is unreachable from any parsed view of the manifest.
    const text = [
      '{',
      '  "devDependencies": {',
      `    "${SDK_PKG}": "file:../sdk-old",`,
      `    "${SDK_PKG}": "file:../sdk-new"`,
      '  }',
      '}',
    ].join('\n');
    expect(countSdkKeyDeclarations(text)).toBe(2);
    // …and the parsed view does NOT — the negative control for this function's
    // existence.
    const parsed = JSON.parse(text) as {
      devDependencies: Record<string, string>;
    };
    expect(Object.keys(parsed.devDependencies)).toHaveLength(1);
  });

  test('zero when the SDK is not declared at all', () => {
    expect(countSdkKeyDeclarations('{"name":"x"}')).toBe(0);
  });
});

