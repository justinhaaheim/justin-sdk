describe('sdkWorkspaceSatisfaction', () => {
  test('a `workspace:` spec on the declaration is enough — home-base’s shape', () => {
    const sb = track(createSandbox());
    writePkg(join(sb.path, 'package.json'), {
      dependencies: {[SDK_PKG]: 'workspace:*'},
      name: 'home-base-like',
      workspaces: ['projects/justin-sdk'],
    });
    const result = sdkWorkspaceSatisfaction(
      sb.path,
      new Map<DepSection, string>([['dependencies', 'workspace:*']]),
    );
    expect(result.satisfied).toBe(true);
    if (!result.satisfied) throw new Error('unreachable');
    expect(result.reason).toContain('workspace:*');
  });

  test('a workspaces MEMBER that IS the SDK is enough on its own', () => {
    // The belt to the `workspace:` spec’s braces: a repo resolving the SDK
    // through its workspaces array without the `workspace:` protocol.
    const sb = track(createSandbox());
    mkdirSync(join(sb.path, 'projects', 'justin-sdk'), {recursive: true});
    writePkg(join(sb.path, 'projects', 'justin-sdk', 'package.json'), {
      name: SDK_PKG,
      version: '0.18.1',
    });
    writePkg(join(sb.path, 'package.json'), {
      dependencies: {[SDK_PKG]: '*'},
      name: 'home-base-like',
      workspaces: ['projects/justin-sdk'],
    });
    const result = sdkWorkspaceSatisfaction(
      sb.path,
      new Map<DepSection, string>([['dependencies', '*']]),
    );
    expect(result.satisfied).toBe(true);
    if (!result.satisfied) throw new Error('unreachable');
    expect(result.reason).toContain('projects/justin-sdk');
  });

  test('a `packages/*` pattern is expanded', () => {
    const sb = track(createSandbox());
    mkdirSync(join(sb.path, 'packages', 'sdk'), {recursive: true});
    writePkg(join(sb.path, 'packages', 'sdk', 'package.json'), {name: SDK_PKG});
    mkdirSync(join(sb.path, 'packages', 'other'), {recursive: true});
    writePkg(join(sb.path, 'packages', 'other', 'package.json'), {
      name: 'other',
    });
    writePkg(join(sb.path, 'package.json'), {
      name: 'monorepo',
      workspaces: ['packages/*'],
    });
    expect(sdkWorkspaceSatisfaction(sb.path, new Map()).satisfied).toBe(true);
  });

  test('an ORDINARY pinned repo is not workspace-satisfied — the guard must not swallow the fleet', () => {
    // Without this, "skip the pin" would apply to all 11 pin consumers and the
    // sweep would silently stop bumping anything.
    const fixture = pinFixture({install: false});
    const declared = readSdkDeclarations(fixture.root);
    if (!declared.ok) throw new Error('unreachable');
    expect(
      sdkWorkspaceSatisfaction(fixture.root, declared.declared).satisfied,
    ).toBe(false);
  });
});

