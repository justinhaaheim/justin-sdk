describe('readSdkDeclarations', () => {
  test('reports each section that declares the SDK, with its spec', () => {
    const fixture = pinFixture({
      install: false,
      sections: ['dependencies', 'devDependencies'],
    });
    expect(declarationsOf(fixture.root)).toEqual({
      dependencies: fixture.oldPin,
      devDependencies: fixture.oldPin,
    });
  });

  test('a manifest declaring the SDK nowhere reads as an empty map, not a failure', () => {
    const fixture = pinFixture({install: false, sections: []});
    const result = readSdkDeclarations(fixture.root);
    expect(result.ok).toBe(true);
    if (!result.ok) throw new Error('unreachable');
    expect([...result.declared.keys()]).toEqual([]);
  });

  test('RULE 5: an unreadable package.json is a failure, NOT "declared nowhere"', () => {
    // The whole fix hangs off this distinction. "Declared nowhere" is the
    // verdict that skips the remove — so a package.json this cannot parse must
    // never be able to produce it, or a stale declaration survives the write.
    const fixture = pinFixture({install: false, sections: ['devDependencies']});
    writeFileSync(fixture.pkgPath, '{ this is not json');
    const result = readSdkDeclarations(fixture.root);
    expect(result.ok).toBe(false);
    if (result.ok) throw new Error('unreachable');
    expect(result.reason).toContain('package.json');
  });

  test('a missing package.json is a failure too', () => {
    const sb = track(createSandbox());
    const result = readSdkDeclarations(sb.path);
    expect(result.ok).toBe(false);
    if (result.ok) throw new Error('unreachable');
    expect(result.reason).toContain('not found');
  });
});

