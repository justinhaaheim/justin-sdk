describe('runSweep --dry-run names the repo that will not be pinned', () => {
  async function captureLog<T>(fn: () => Promise<T>): Promise<string> {
    const original = console.log;
    let out = '';
    console.log = (...args: unknown[]) => {
      out += `${args.join(' ')}\n`;
    };
    try {
      await fn();
    } finally {
      console.log = original;
    }
    return out;
  }

  test('a workspace consumer is flagged in the plan; a pinned repo is not', async () => {
    // The plan is what an operator reads BEFORE authorizing a fleet-wide run
    // that commits and pushes. "would sweep off main" is the same line for a
    // repo that gets a pin bump and for one that structurally cannot — so the
    // difference has to be on the plan line itself.
    const sb = track(createSandbox());
    const pinned = initRepo(sb, 'pinned', {
      'justin-sdk.config.json': `${JSON.stringify({components: ['base-setup']}, null, 2)}\n`,
      'package.json': `${JSON.stringify(
        {
          devDependencies: {
            [SDK_PKG]: 'github:justinhaaheim/justin-sdk#v0.9.0',
          },
          name: 'pinned',
          version: '0.0.1',
        },
        null,
        2,
      )}\n`,
    });
    const workspace = initRepo(sb, 'workspace-consumer', {
      'justin-sdk.config.json': `${JSON.stringify({components: ['base-setup']}, null, 2)}\n`,
      'package.json': `${JSON.stringify(
        {
          dependencies: {[SDK_PKG]: 'workspace:*'},
          name: 'workspace-consumer',
          version: '0.0.1',
          workspaces: ['projects/justin-sdk'],
        },
        null,
        2,
      )}\n`,
    });

    const out = await captureLog(() =>
      runSweep({dryRun: true, repos: [pinned, workspace]}),
    );

    // Strip the summary's own SGR codes so the assertion is about words.
    const plain = out.replace(/\x1b\[[0-9;]*m/g, '');
    const lineFor = (name: string): string =>
      plain.split('\n').find((line) => line.trim().startsWith(`= ${name} `)) ??
      '';

    expect(lineFor('workspace-consumer')).toContain(
      'would sweep off main — pin: workspace-satisfied, would NOT be written',
    );
    // The ordinary repo's line is unchanged — the flag is not decoration.
    expect(lineFor('pinned').trim()).toBe('= pinned would sweep off main');
  });
});
