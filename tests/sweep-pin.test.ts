describe('verifySinglePin', () => {
  const PIN = 'github:justinhaaheim/justin-sdk#v0.18.1';
  const map = (
    entries: Record<string, string>,
  ): ReadonlyMap<DepSection, string> =>
    new Map(Object.entries(entries) as Array<[DepSection, string]>);

  test('exactly one devDependencies declaration at the pin is the contract', () => {
    expect(verifySinglePin(map({devDependencies: PIN}), PIN)).toEqual({
      ok: true,
    });
  });

  test('two declarations fail, and the reason names both', () => {
    const result = verifySinglePin(
      map({
        dependencies: 'github:justinhaaheim/justin-sdk#v0.9.0',
        devDependencies: PIN,
      }),
      PIN,
    );
    expect(result.ok).toBe(false);
    if (result.ok) throw new Error('unreachable');
    expect(result.reason).toContain('v0.9.0');
    expect(result.reason).toContain(PIN);
  });

  test('the right pin in the wrong section fails (the yarn shape)', () => {
    const result = verifySinglePin(map({dependencies: PIN}), PIN);
    expect(result.ok).toBe(false);
    if (result.ok) throw new Error('unreachable');
    expect(result.reason).toContain('dependencies');
  });

  test('the right section at the wrong spec fails', () => {
    const result = verifySinglePin(
      map({devDependencies: 'github:justinhaaheim/justin-sdk#v0.9.0'}),
      PIN,
    );
    expect(result.ok).toBe(false);
    if (result.ok) throw new Error('unreachable');
    expect(result.reason).toContain('not the swept pin');
  });

  test('no declaration at all fails — a vanished pin is not a clean pin', () => {
    const result = verifySinglePin(map({}), PIN);
    expect(result.ok).toBe(false);
    if (result.ok) throw new Error('unreachable');
    expect(result.reason).toContain('neither');
  });
});

