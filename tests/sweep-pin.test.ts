type Manager = 'bun' | 'npm' | 'yarn';

interface PinFixture {
  root: string;
  pkgPath: string;
  /** The pin `writeSdkPin` is asked to land. */
  newPin: string;
  /** The stale spec the fixture starts out declaring. */
  oldPin: string;
  read: () => string;
}

function writePkg(path: string, pkg: unknown): void {
  writeFileSync(path, `${JSON.stringify(pkg, null, 2)}\n`);
}

/**
 * A repo declaring the SDK in `sections`, at a stale local spec, with a
 * lockfile of the right flavour so detectPackageManager picks `manager`.
 *
 * The lockfile is generated by really running `<manager> install`, not stubbed:
 * `yarn remove` HARD-FAILS without one ("error No lockfile in this directory"),
 * which is a real behaviour the pin step has to survive rather than a detail to
 * fake away.
 */
function pinFixture(options: {
  manager?: Manager;
  sections?: readonly DepSection[];
  install?: boolean;
}): PinFixture {
  const manager = options.manager ?? 'bun';
  const sections = options.sections ?? ['devDependencies'];
  const install = options.install ?? true;

  const sb = track(createSandbox());
  // Two stand-in SDK packages so "old spec" and "new spec" are genuinely
  // different resolutions, exactly as two github commits would be.
  for (const [dir, version] of [
    ['sdk-old', '0.0.1'],
    ['sdk-new', '0.0.2'],
  ] as const) {
    mkdirSync(join(sb.path, dir), {recursive: true});
    writePkg(join(sb.path, dir, 'package.json'), {name: SDK_PKG, version});
  }

  const root = join(sb.path, 'repo');
  mkdirSync(root, {recursive: true});
  const oldPin = 'file:../sdk-old';
  const newPin = 'file:../sdk-new';

  const pkg: Record<string, unknown> = {name: 'fixture', version: '0.0.1'};
  for (const section of sections) pkg[section] = {[SDK_PKG]: oldPin};
  const pkgPath = join(root, 'package.json');
  writePkg(pkgPath, pkg);

  if (install) {
    // Quiet, offline: a file: dependency never reaches a registry.
    execFileSync(manager, ['install'], {cwd: root, stdio: 'ignore'});
  } else if (manager !== 'bun') {
    throw new Error('install:false only makes sense for the bun fixture');
  }

  return {
    newPin,
    oldPin,
    pkgPath,
    read: () => readFileSync(pkgPath, 'utf-8'),
    root,
  };
}

/** Parsed declarations of a fixture, as a plain object for readable asserts. */
function declarationsOf(root: string): Record<string, string> {
  const result = readSdkDeclarations(root);
  if (!result.ok) throw new Error(`unreadable fixture: ${result.reason}`);
  return Object.fromEntries(result.declared);
}

