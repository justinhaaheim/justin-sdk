describe('writeSdkPin — bun, every fleet manifest shape (AC1-AC3)', () => {
  test('devDependencies at an OLD spec: the pin lands, exactly once (AC1 shape)', () => {
    const fixture = pinFixture({sections: ['devDependencies']});
    const result = writeSdkPin(fixture.root, fixture.newPin);
    expect(result.ok).toBe(true);
    if (!result.ok) throw new Error(result.detail);
    expect(declarationsOf(fixture.root)).toEqual({
      devDependencies: fixture.newPin,
    });
    expect(countSdkKeyDeclarations(fixture.read())).toBe(1);
  });

  test('NEGATIVE CONTROL: `bun add -d` over that same fixture writes the key TWICE', () => {
    // The offline face of the bug. With a GITHUB spec this same precondition
    // produces the `DependencyLoop` that stopped the maiden sweep (measured on
    // home-base-apus.1, four arms); with a `file:` spec bun instead corrupts
    // the manifest with a duplicate key. Same precondition, same fix, and this
    // arm is the one that can be automated.
    const fixture = pinFixture({sections: ['devDependencies']});
    execFileSync('bun', ['add', '-d', fixture.newPin], {
      cwd: fixture.root,
      stdio: 'ignore',
    });
    expect(countSdkKeyDeclarations(fixture.read())).toBe(2);
  });

  test('dependencies only: normalized into devDependencies, exactly once (AC2)', () => {
    const fixture = pinFixture({sections: ['dependencies']});
    const result = writeSdkPin(fixture.root, fixture.newPin);
    expect(result.ok).toBe(true);
    if (!result.ok) throw new Error(result.detail);
    expect(declarationsOf(fixture.root)).toEqual({
      devDependencies: fixture.newPin,
    });
    expect(countSdkKeyDeclarations(fixture.read())).toBe(1);
    // The normalization is REPORTED, not silent — it changes the manifest’s
    // shape, so it has to be visible in the sweep summary.
    expect(result.summaryNote).toContain('dependencies → devDependencies');
  });

  test('NEGATIVE CONTROL: `bun add -d` over that same fixture leaves TWO declarations', () => {
    // health-logger-rn d14c327, committed and pushed: `dependencies` #v0.9.0
    // beside `devDependencies` #v0.18.0.
    const fixture = pinFixture({sections: ['dependencies']});
    execFileSync('bun', ['add', '-d', fixture.newPin], {
      cwd: fixture.root,
      stdio: 'ignore',
    });
    expect(declarationsOf(fixture.root)).toEqual({
      dependencies: fixture.oldPin,
      devDependencies: fixture.newPin,
    });
  });

  test('BOTH sections (the ynab-mcp-deluxe shape): ends with exactly one (AC3)', () => {
    const fixture = pinFixture({
      sections: ['dependencies', 'devDependencies'],
    });
    const result = writeSdkPin(fixture.root, fixture.newPin);
    expect(result.ok).toBe(true);
    if (!result.ok) throw new Error(result.detail);
    expect(declarationsOf(fixture.root)).toEqual({
      devDependencies: fixture.newPin,
    });
    expect(countSdkKeyDeclarations(fixture.read())).toBe(1);
  });

  test('NEGATIVE CONTROL: `bun add -d` over the both-sections fixture leaves two', () => {
    const fixture = pinFixture({
      sections: ['dependencies', 'devDependencies'],
    });
    execFileSync('bun', ['add', '-d', fixture.newPin], {
      cwd: fixture.root,
      stdio: 'ignore',
    });
    expect(Object.keys(declarationsOf(fixture.root)).sort()).toEqual([
      'dependencies',
      'devDependencies',
    ]);
  });

  test('a repo declaring the SDK nowhere still gets the pin', () => {
    // The enrollment path: nothing to remove, the add is the whole step.
    const fixture = pinFixture({sections: []});
    const result = writeSdkPin(fixture.root, fixture.newPin);
    expect(result.ok).toBe(true);
    if (!result.ok) throw new Error(result.detail);
    expect(declarationsOf(fixture.root)).toEqual({
      devDependencies: fixture.newPin,
    });
    expect(result.summaryNote).toBeUndefined();
  });
});

describe('writeSdkPin — npm and yarn (AC4)', () => {
  test('npm: a `dependencies` declaration is normalized into devDependencies', () => {
    const fixture = pinFixture({manager: 'npm', sections: ['dependencies']});
    const result = writeSdkPin(fixture.root, fixture.newPin);
    expect(result.ok).toBe(true);
    if (!result.ok) throw new Error(result.detail);
    expect(declarationsOf(fixture.root)).toEqual({
      devDependencies: fixture.newPin,
    });
  });

  test('yarn: same, and the remove is what makes it true', () => {
    const fixture = pinFixture({manager: 'yarn', sections: ['dependencies']});
    const result = writeSdkPin(fixture.root, fixture.newPin);
    expect(result.ok).toBe(true);
    if (!result.ok) throw new Error(result.detail);
    expect(declarationsOf(fixture.root)).toEqual({
      devDependencies: fixture.newPin,
    });
  });

  test('NEGATIVE CONTROL: `yarn add --dev` alone updates the spec IN `dependencies`', () => {
    // yarn’s own failure mode, and the reason the remove is not npm-only
    // ceremony: the `--dev` is silently ignored for an already-declared
    // package, so the SDK would stay a runtime dependency forever.
    const fixture = pinFixture({manager: 'yarn', sections: ['dependencies']});
    execFileSync('yarn', ['add', '--dev', fixture.newPin], {
      cwd: fixture.root,
      stdio: 'ignore',
    });
    expect(declarationsOf(fixture.root)).toEqual({
      dependencies: fixture.newPin,
    });
  });

  test('a failing ADD is reported red, and the manifest is left declaring nothing rather than something wrong', () => {
    // The one cost of remove-then-add: between the two commands the repo
    // declares no SDK at all. That window is safe by construction — a red
    // payload returns before the sweep's commit step, so this state can only
    // ever be seen in a standing worktree — but the failure has to be LOUD, or
    // "the pin did not land" becomes indistinguishable from "already current".
    //
    // (The other failure this guard covers, a red REMOVE, is not reachable
    // through the sweep for yarn the way it first appeared: `yarn remove`
    // errors "No lockfile in this directory", but detectPackageManager only
    // selects yarn BECAUSE a yarn.lock exists — and an empty one satisfies
    // yarn. Measured, rather than assumed from the error text.)
    const fixture = pinFixture({sections: ['devDependencies']});
    const result = writeSdkPin(fixture.root, 'file:../no-such-package');
    expect(result.ok).toBe(false);
    if (result.ok) throw new Error('unreachable');
    expect(result.detail).toContain('bun add');
    expect(declarationsOf(fixture.root)).toEqual({});
  });
});

describe('writeSdkPin — the workspace consumer (D21)', () => {
  function homeBaseLike(): {root: string; read: () => string} {
    const sb = track(createSandbox());
    const root = join(sb.path, 'repo');
    mkdirSync(join(root, 'projects', 'justin-sdk'), {recursive: true});
    writePkg(join(root, 'projects', 'justin-sdk', 'package.json'), {
      name: SDK_PKG,
      version: '0.18.1',
    });
    mkdirSync(join(sb.path, 'sdk-new'), {recursive: true});
    writePkg(join(sb.path, 'sdk-new', 'package.json'), {name: SDK_PKG});
    writePkg(join(root, 'package.json'), {
      dependencies: {[SDK_PKG]: 'workspace:*'},
      name: 'home-base-like',
      version: '0.0.1',
      workspaces: ['projects/justin-sdk'],
    });
    return {
      read: () => readFileSync(join(root, 'package.json'), 'utf-8'),
      root,
    };
  }

  test('the pin is NOT written, the manifest is byte-identical, and the skip is REPORTED', () => {
    const project = homeBaseLike();
    const before = project.read();

    const result = writeSdkPin(project.root, 'file:../sdk-new');

    expect(result.ok).toBe(true);
    if (!result.ok) throw new Error(result.detail);
    expect(project.read()).toBe(before);
    // Never silent, never conflated with "pinned" (D21).
    expect(result.note).toContain('workspace-satisfied');
    expect(result.summaryNote).toBe('pin: workspace-satisfied, not written');
  });

  test('NEGATIVE CONTROL: the un-skipped write converts it to a github-pin consumer', () => {
    // What a full sweep of home-base did before D21 — and it would have gone
    // GREEN: a second declaration beside `workspace:*`, on the repo that hosts
    // the SDK’s own development loop.
    const project = homeBaseLike();
    execFileSync('bun', ['add', '-d', 'file:../sdk-new'], {
      cwd: project.root,
      stdio: 'ignore',
    });
    const declared = declarationsOf(project.root);
    expect(declared.dependencies).toBe('workspace:*');
    expect(declared.devDependencies).toBe('file:../sdk-new');
  });
});

